"""The VM bootstrap script shared by the cloud backends."""

from __future__ import annotations

import shlex
from typing import List

from ..davi import DaviConfig


def train_args(cfg: DaviConfig, run_dir: str) -> List[str]:
    args = []
    for key, value in cfg.to_dict().items():
        if key in ("run_dir", "gpss_bin") or value is None or value == "":
            continue
        args += ["--" + key.replace("_", "-"), str(value)]
    return args + ["--run-dir", run_dir]


def bootstrap_script(cfg: DaviConfig, *, repo: str, ref: str, max_hours: float, upload: str, artefacts: str) -> str:
    """A cloud-init/startup script: watchdog, toolchain, build, train, export, upload, power off.

    ``upload`` is a shell command template with ``{src}``/``{dst}`` placeholders.
    """
    run_dir = "/opt/gpss/run"
    minutes = max(1, int(max_hours * 60))
    # Stop training before the kill switch so export + upload still run on the last checkpoint.
    train_minutes = max(1, minutes - max(5, min(15, minutes // 4)))
    train = shlex.join(["python3", "-u", "-m", "gpss_train", "train", *train_args(cfg, run_dir), "--resume"])
    out = f"/opt/gpss/weights/{cfg.puzzle}-davi"
    up = upload.format(src="/opt/gpss/out", dst=shlex.quote(artefacts))
    return f"""#!/bin/bash
# gpss DAVI training bootstrap (generated by gpss_train.launch; see docs/training.md).
set -euxo pipefail
# Kill switch 1: power off (= terminate/delete, see instance settings) after {max_hours} h.
shutdown -h +{minutes}
trap 'shutdown -h now' EXIT
export DEBIAN_FRONTEND=noninteractive HOME=/root
apt-get update && apt-get install -y build-essential git python3-pip curl
curl --proto '=https' --tlsv1.2 -sSf https://sh.rustup.rs | sh -s -- -y --profile minimal
source /root/.cargo/env
git clone {shlex.quote(repo)} /opt/gpss/src && cd /opt/gpss/src && git checkout {shlex.quote(ref)}
pip3 install -r training/requirements.txt
cargo build --release -p gpss-cli
export GPSS_BIN=/opt/gpss/src/target/release/gpss
mkdir -p /opt/gpss/out
cd training
set +e
timeout --signal=INT --kill-after=2m {train_minutes}m {train} 2>&1 | tee /opt/gpss/out/train.log
status=${{PIPESTATUS[0]}}
set -e
# 124: stopped by the time limit (planned; resume later). Anything else is a training
# failure: still export + upload the last checkpoint for diagnosis, but mark it and fail.
case $status in
  0) ;;
  124) echo "time limit reached; uploading the last checkpoint" > /opt/gpss/out/TIME_LIMIT ;;
  *) echo "training failed with exit $status" > /opt/gpss/out/TRAINING_FAILED ;;
esac
python3 -m gpss_train export --checkpoint {run_dir}/checkpoint.pt --out {out}
cp -r {run_dir}/log.jsonl {run_dir}/config.json {run_dir}/checkpoint.pt /opt/gpss/weights/* /opt/gpss/out/
{up}
if [ -e /opt/gpss/out/TRAINING_FAILED ]; then exit "$status"; fi
"""

//! The 48 symmetries of the cube and conjugation of positions by them.
//!
//! A symmetry is a rotation or reflection of the whole cube. Conjugating a position `C`
//! by a symmetry `g` means "look at `C` through `g`": every sticker at location `x`
//! with colour `c` moves to location `g(x)` and is recoloured `g(c)`. The result,
//! `conjugate(C, g)`, is again a legal position, and it is exactly as far from solved
//! as `C`, because `g` turns every face turn into a face turn (a reflection turns
//! clockwise turns into anticlockwise ones). This is the fact that lets Kociemba
//! store one pruning-table entry per *symmetry class* [Koc], and lets an optimal solver
//! look a position up in a pattern database several times, once per conjugate.
//!
//! # Indexing
//!
//! Following Kociemba [KocImp], the symmetries are generated by four basic ones:
//!
//! * `URF3`: rotation by 120 degrees about the URF-DBL diagonal (`U -> R -> F -> U`);
//! * `F2`: rotation by 180 degrees about the F-B axis;
//! * `U4`: rotation by 90 degrees about the U-D axis (a whole-cube `U` turn);
//! * `LR2`: the reflection that swaps left and right.
//!
//! Symmetry number `s = 16a + 8b + 2c + d` is `URF3^a . F2^b . U4^c . LR2^d` (applied
//! right to left). The first [`N_SYM_D4H`] = 16 (those with `a = 0`) are the symmetries
//! that keep the U-D axis in place, the group `D4h`; they map the two-phase subgroup
//! `G1 = <U, D, R2, L2, F2, B2>` to itself, which is what [`super::twophase`] needs.
//! Odd `s` are reflections.
//!
//! # Implementation
//!
//! Everything is derived from a small geometric model at first use instead of being
//! typed in: faces are unit normal vectors, a cubie position is the set of faces it
//! touches, and a symmetry is the induced permutation of the six faces. From that we
//! build, for each symmetry, per-cubie "recipes" (`position, cubie, orientation ->
//! position', cubie', orientation'`), so [`conjugate`] is 20 table lookups and no
//! group multiplication with mirrored orientations is needed. Unit tests check the
//! model against the hand-written move tables in [`super`], and property tests check
//! that conjugation is a group action and an automorphism (see `cube3/tests.rs`).
//!
//! [Koc]: https://kociemba.org/math/twophase.htm
//! [KocImp]: https://kociemba.org/math/imptwophase.htm

use super::Cube3State;
use std::sync::OnceLock;

/// Number of cube symmetries (24 rotations and 24 reflections).
pub const N_SYM: usize = 48;
/// Number of symmetries that preserve the U-D axis (`D4h`); they are `0..16`.
pub const N_SYM_D4H: usize = 16;

type Vec3 = [i8; 3];

/// Outward normals of the faces in `Face` order `U R F D L B` (x = R, y = U, z = F).
const NORMALS: [Vec3; 6] = [
    [0, 1, 0],
    [1, 0, 0],
    [0, 0, 1],
    [0, -1, 0],
    [-1, 0, 0],
    [0, 0, -1],
];
const U: u8 = 0;
const R: u8 = 1;
const F: u8 = 2;
const D: u8 = 3;
const L: u8 = 4;
const B: u8 = 5;

/// Faces of each corner position in Kociemba's facelet order: the U/D facelet first,
/// then clockwise. Corner `i` of a position is also the cubie whose home is `i`.
pub(crate) const CORNER_FACES: [[u8; 3]; 8] = [
    [U, R, F],
    [U, F, L],
    [U, L, B],
    [U, B, R],
    [D, F, R],
    [D, L, F],
    [D, B, L],
    [D, R, B],
];

/// Faces of each edge position in Kociemba's facelet order (reference facelet first).
pub(crate) const EDGE_FACES: [[u8; 2]; 12] = [
    [U, R],
    [U, F],
    [U, L],
    [U, B],
    [D, R],
    [D, F],
    [D, L],
    [D, B],
    [F, R],
    [F, L],
    [B, L],
    [B, R],
];

/// A permutation of the six faces induced by a rotation or reflection of the cube:
/// `map[f]` is the face that `f` is carried to.
pub(crate) type FaceMap = [u8; 6];

fn face_of(v: Vec3) -> u8 {
    NORMALS
        .iter()
        .position(|&n| n == v)
        .expect("not a face normal") as u8
}

fn face_map(f: impl Fn(Vec3) -> Vec3) -> FaceMap {
    std::array::from_fn(|i| face_of(f(NORMALS[i])))
}

/// `a` after `b`.
fn compose(a: &FaceMap, b: &FaceMap) -> FaceMap {
    std::array::from_fn(|f| a[b[f] as usize])
}

/// The rotation carrying out a clockwise quarter turn of `face` (seen from outside):
/// by -90 degrees about its normal `n`, `v -> n (n . v) - n x v`.
pub(crate) fn clockwise(face: u8) -> FaceMap {
    let n = NORMALS[face as usize];
    face_map(|v| {
        let dot = n[0] * v[0] + n[1] * v[1] + n[2] * v[2];
        let cross = [
            n[1] * v[2] - n[2] * v[1],
            n[2] * v[0] - n[0] * v[2],
            n[0] * v[1] - n[1] * v[0],
        ];
        std::array::from_fn(|i| n[i] * dot - cross[i])
    })
}

/// Whether a face map is a reflection (reverses the cyclic order of the faces around
/// the URF corner).
fn is_reflection(g: &FaceMap) -> bool {
    let [a, b, c] = [g[U as usize], g[R as usize], g[F as usize]].map(|f| NORMALS[f as usize]);
    let det = a[0] as i32 * (b[1] as i32 * c[2] as i32 - b[2] as i32 * c[1] as i32)
        - a[1] as i32 * (b[0] as i32 * c[2] as i32 - b[2] as i32 * c[0] as i32)
        + a[2] as i32 * (b[0] as i32 * c[1] as i32 - b[1] as i32 * c[0] as i32);
    // det(U, R, F) of the identity is det(e_y, e_x, e_z) = -1.
    det == 1
}

fn index_of_set<const K: usize>(table: &[[u8; K]], faces: [u8; K]) -> usize {
    let mut want = faces;
    want.sort_unstable();
    table
        .iter()
        .position(|p| {
            let mut s = *p;
            s.sort_unstable();
            s == want
        })
        .expect("no cubie position with these faces")
}

/// Where the cubie `c` (orientation `o`) sitting in position `p` ends up after
/// conjugation by `g`: `(position', cubie', orientation')`.
///
/// Sticker slot `k` of position `p` shows colour `faces[c][(k - o) mod K]` (Kociemba's
/// facelet convention); it moves to the slot of the face `g(faces[p][k])` and is
/// recoloured by `g`.
fn cubie_conj<const K: usize>(
    table: &[[u8; K]],
    g: &FaceMap,
    p: usize,
    c: usize,
    o: usize,
) -> (u8, u8, u8) {
    let mut colour = [0u8; K];
    for k in 0..K {
        colour[(k + o) % K] = table[c][k];
    }
    let p2 = index_of_set(table, table[p].map(|f| g[f as usize]));
    let mut colour2 = [0u8; K];
    for k in 0..K {
        let slot = table[p2]
            .iter()
            .position(|&f| f == g[table[p][k] as usize])
            .unwrap();
        colour2[slot] = g[colour[k] as usize];
    }
    let c2 = index_of_set(table, colour2);
    // The reference colour of every cubie is its first face; its slot is the orientation.
    let o2 = colour2.iter().position(|&x| x == table[c2][0]).unwrap();
    debug_assert!(
        (0..K).all(|k| colour2[(k + o2) % K] == table[c2][k]),
        "mirrored cubie"
    );
    (p2 as u8, c2 as u8, o2 as u8)
}

/// Per-symmetry lookup tables for [`conjugate`].
pub struct SymTables {
    /// Face permutation of each symmetry.
    pub faces: [FaceMap; N_SYM],
    /// `mult[a][b]` is the symmetry "`b`, then `a`".
    pub mult: [[u8; N_SYM]; N_SYM],
    /// `inv[a]` is the inverse of symmetry `a`.
    pub inv: [u8; N_SYM],
    corner_pos: [[u8; 8]; N_SYM],
    corner_ori: Vec<[[[u8; 3]; 8]; 8]>,
    edge_pos: [[u8; 12]; N_SYM],
    edge_ori: Vec<[[[u8; 2]; 12]; 12]>,
    /// `move_conj[m][s]`: the move (in `FaceTurn::all()` order) that move `m` becomes
    /// under conjugation by `s`.
    pub move_conj: [[u8; N_SYM]; 18],
}

fn build() -> SymTables {
    let urf3: FaceMap = [R, F, U, L, B, D];
    let f2 = compose(&clockwise(F), &clockwise(F));
    let u4 = clockwise(U);
    let lr2: FaceMap = [U, L, F, D, R, B];
    let id: FaceMap = [0, 1, 2, 3, 4, 5];
    let pow = |g: &FaceMap, k: usize| (0..k).fold(id, |acc, _| compose(&acc, g));
    let faces: [FaceMap; N_SYM] = std::array::from_fn(|s| {
        let (a, b, c, d) = (s / 16, (s / 8) % 2, (s / 2) % 4, s % 2);
        compose(
            &pow(&urf3, a),
            &compose(&pow(&f2, b), &compose(&pow(&u4, c), &pow(&lr2, d))),
        )
    });
    let find = |g: FaceMap| faces.iter().position(|&h| h == g).unwrap() as u8;
    let mult =
        std::array::from_fn(|a| std::array::from_fn(|b| find(compose(&faces[a], &faces[b]))));
    let inv = std::array::from_fn(|a| {
        (0..N_SYM)
            .find(|&b| compose(&faces[a], &faces[b]) == id)
            .unwrap() as u8
    });
    let mut corner_pos = [[0u8; 8]; N_SYM];
    let mut corner_ori = vec![[[[0u8; 3]; 8]; 8]; N_SYM];
    let mut edge_pos = [[0u8; 12]; N_SYM];
    let mut edge_ori = vec![[[[0u8; 2]; 12]; 12]; N_SYM];
    for (s, g) in faces.iter().enumerate() {
        for p in 0..8 {
            for (c, oris) in corner_ori[s][p].iter_mut().enumerate() {
                for (o, out) in oris.iter_mut().enumerate() {
                    let (p2, c2, o2) = cubie_conj(&CORNER_FACES, g, p, c, o);
                    corner_pos[s][p] = p2;
                    if p == c {
                        debug_assert_eq!(p2, c2);
                    }
                    *out = o2;
                }
            }
        }
        for p in 0..12 {
            for (c, oris) in edge_ori[s][p].iter_mut().enumerate() {
                for (o, out) in oris.iter_mut().enumerate() {
                    let (p2, _, o2) = cubie_conj(&EDGE_FACES, g, p, c, o);
                    edge_pos[s][p] = p2;
                    *out = o2;
                }
            }
        }
    }
    let mut t = SymTables {
        faces,
        mult,
        inv,
        corner_pos,
        corner_ori,
        edge_pos,
        edge_ori,
        move_conj: [[0; N_SYM]; 18],
    };
    let moves = super::move_table();
    for m in 0..18 {
        for s in 0..N_SYM {
            let c = t.conjugate(&moves[m], s);
            t.move_conj[m][s] = moves
                .iter()
                .position(|x| *x == c)
                .expect("conjugate of a face turn is not a face turn")
                as u8;
        }
    }
    t
}

impl SymTables {
    /// The edges of `state` conjugated by symmetry `s` (corners left solved): half the
    /// work of [`SymTables::conjugate`] for lookups that only read edges.
    #[inline]
    pub fn conjugate_edges(&self, state: &Cube3State, s: usize) -> Cube3State {
        let mut out = Cube3State::SOLVED;
        let (epos, eori) = (&self.edge_pos[s], &self.edge_ori[s]);
        for p in 0..12 {
            let (c, o) = (state.ep[p] as usize, state.eo[p] as usize);
            let q = epos[p] as usize;
            out.ep[q] = epos[c];
            out.eo[q] = eori[p][c][o];
        }
        out
    }

    /// `state` conjugated by symmetry `s`; see the module documentation.
    #[inline]
    pub fn conjugate(&self, state: &Cube3State, s: usize) -> Cube3State {
        let mut out = Cube3State::SOLVED;
        let (cpos, cori) = (&self.corner_pos[s], &self.corner_ori[s]);
        for p in 0..8 {
            let (c, o) = (state.cp[p] as usize, state.co[p] as usize);
            let q = cpos[p] as usize;
            out.cp[q] = cpos[c];
            out.co[q] = cori[p][c][o];
        }
        let (epos, eori) = (&self.edge_pos[s], &self.edge_ori[s]);
        for p in 0..12 {
            let (c, o) = (state.ep[p] as usize, state.eo[p] as usize);
            let q = epos[p] as usize;
            out.ep[q] = epos[c];
            out.eo[q] = eori[p][c][o];
        }
        out
    }

    /// Whether symmetry `s` is a reflection.
    pub fn is_reflection(&self, s: usize) -> bool {
        is_reflection(&self.faces[s])
    }
}

/// The process-wide symmetry tables (built in well under a millisecond).
pub fn tables() -> &'static SymTables {
    static T: OnceLock<SymTables> = OnceLock::new();
    T.get_or_init(build)
}

/// Index of the 120-degree rotation about the URF-DBL diagonal taking U to R, R to F
/// and F to U. It and its square map the U-D axis to the R-L and F-B axes, which is what
/// the two-phase "six directions" and Korf's extra lookups need.
pub fn urf3() -> usize {
    let t = tables();
    (0..N_SYM)
        .find(|&s| t.faces[s][..3] == [R, F, U])
        .expect("the URF diagonal rotation is a cube symmetry")
}

/// `state` conjugated by symmetry `s` (`0..N_SYM`).
pub fn conjugate(state: &Cube3State, s: usize) -> Cube3State {
    tables().conjugate(state, s)
}

/// Sticker-level picture of a position, used to check the cubie model against the
/// geometry in tests: `corners[p][k]` is the colour (home face) on slot `k` of corner
/// position `p`, and likewise for edges.
#[cfg(test)]
#[derive(Clone, PartialEq, Eq, Debug)]
pub(crate) struct Facelets {
    pub corners: [[u8; 3]; 8],
    pub edges: [[u8; 2]; 12],
}

#[cfg(test)]
impl Facelets {
    #[allow(clippy::needless_range_loop)]
    pub fn from_state(s: &Cube3State) -> Self {
        let mut f = Facelets {
            corners: [[0; 3]; 8],
            edges: [[0; 2]; 12],
        };
        for p in 0..8 {
            for k in 0..3 {
                f.corners[p][(k + s.co[p] as usize) % 3] = CORNER_FACES[s.cp[p] as usize][k];
            }
        }
        for p in 0..12 {
            for k in 0..2 {
                f.edges[p][(k + s.eo[p] as usize) % 2] = EDGE_FACES[s.ep[p] as usize][k];
            }
        }
        f
    }

    /// Turn the layer of `face` clockwise: stickers on positions touching `face` move
    /// with the rotation, keeping their colours.
    pub fn turn(&self, face: u8) -> Self {
        let g = clockwise(face);
        let mut out = self.clone();
        for p in 0..8 {
            if CORNER_FACES[p].contains(&face) {
                let p2 = index_of_set(&CORNER_FACES, CORNER_FACES[p].map(|f| g[f as usize]));
                for k in 0..3 {
                    let slot = CORNER_FACES[p2]
                        .iter()
                        .position(|&f| f == g[CORNER_FACES[p][k] as usize])
                        .unwrap();
                    out.corners[p2][slot] = self.corners[p][k];
                }
            }
        }
        for p in 0..12 {
            if EDGE_FACES[p].contains(&face) {
                let p2 = index_of_set(&EDGE_FACES, EDGE_FACES[p].map(|f| g[f as usize]));
                for k in 0..2 {
                    let slot = EDGE_FACES[p2]
                        .iter()
                        .position(|&f| f == g[EDGE_FACES[p][k] as usize])
                        .unwrap();
                    out.edges[p2][slot] = self.edges[p][k];
                }
            }
        }
        out
    }
}
